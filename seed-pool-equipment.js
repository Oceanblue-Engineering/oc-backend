async function seedData() {
  try {
    console.log("Connecting to MongoDB...");
    await mongoose.connect(MONGODB_URI);
    console.log("Connected successfully!");

    console.log("Hiding existing products...");
    const result = await Inventory.updateMany(
      {},
      { $set: { status: "inactive" } }
    );
    console.log(`Updated ${result.modifiedCount} existing products to inactive.`);

    console.log("Inserting swimming pool equipment...");
    for (const item of poolEquipment) {
      // Check if productCode already exists
      const existing = await Inventory.findOne({ productCode: item.productCode });
      if (existing) {
        // Just update it if it exists
        await Inventory.updateOne({ productCode: item.productCode }, item);
      } else {
        await Inventory.create(item);
      }
    }
    console.log("Swimming pool equipment seeded successfully!");

    process.exit(0);
  } catch (error) {
    console.error("Error seeding data:", error);
    process.exit(1);
  }
}

seedData();
